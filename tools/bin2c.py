#!/usr/bin/env python3
"""bin2c.py -- turn a binary blob into a PROGMEM C array header.

Used by firmware/avr-1284p/Makefile to bake firmware/z80-boot-rom/cpm/
stage1.bin into the AVR flash image (see that Makefile and monitor.c's
start_from_stage1()). Output is deterministic -- fixed 12 bytes/line,
lowercase hex -- so regenerating on any machine produces a byte-identical
file and `git status` stays quiet unless the input actually changed.

Usage:  bin2c.py --name <symbol> <blob>   > out.h
"""
import argparse
import pathlib
import sys

WRAP = 12  # bytes per line

parser = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("--name", required=True,
                    help="C identifier for the array (also the header guard / size macro stem)")
parser.add_argument("blob", help="path to the binary file")
args = parser.parse_args()

data = pathlib.Path(args.blob).read_bytes()
name = args.name
guard = name.upper() + "_H"
size_macro = name.upper() + "_SIZE"
src = pathlib.Path(args.blob).name

out = sys.stdout
out.write(f"/* Generated by tools/bin2c.py from {src} -- do not edit.\n")
out.write(" * Regenerated by firmware/avr-1284p/Makefile on every build; a dirty diff\n")
out.write(" * here means the source .asm changed and the .hex needs a rebuild+reflash. */\n")
out.write(f"#ifndef {guard}\n#define {guard}\n\n")
out.write("#include <stdint.h>\n#include <avr/pgmspace.h>\n\n")
out.write(f"#define {size_macro} {len(data)}u\n\n")
out.write(f"static const uint8_t {name}[{size_macro}] PROGMEM = {{\n")
for i in range(0, len(data), WRAP):
    chunk = data[i:i + WRAP]
    out.write("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",\n")
out.write("};\n\n")
out.write(f"_Static_assert({size_macro} <= 8192u,\n")
out.write(f'    "{src} does not fit the 8K rom_buf ROM-emulation window");\n\n')
out.write(f"#endif /* {guard} */\n")
